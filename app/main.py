
import streamlit as st
from app.chatbot import answer_question

st.set_page_config(
    page_title="YGF AI Security Lab",
    page_icon="🛡️",
    layout="centered"
)

st.title("🛡️ YGF AI Security Testing Lab")
st.caption("A controlled security-testing POC using fictional company data.")

provider = st.selectbox(
    "Choose AI model",
    ["Mock", "Gemini", "Claude"]
)

if provider == "Mock":
    st.info("Mock mode: responses are simulated, not generated by a real AI model.")
else:
    st.warning("This option requires a working API key and may incur charges.")

if "messages" not in st.session_state:
    st.session_state.messages = []

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

if prompt := st.chat_input("Ask DewDrop Botanics a question..."):
    st.session_state.messages.append(
        {"role": "user", "content": prompt}
    )

    with st.chat_message("user"):
        st.markdown(prompt)

    try:
        response = answer_question(prompt, provider=provider)
    except Exception as error:
        response = f"Error: {error}"

    st.session_state.messages.append(
        {"role": "assistant", "content": response}
    )

    with st.chat_message("assistant"):
        st.markdown(response)

if st.button("Clear conversation"):
    st.session_state.messages = []
    st.rerun()
